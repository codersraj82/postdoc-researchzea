export function getSampleJobs(referenceDate = new Date()) {
  const stableReference = new Date(referenceDate);
  stableReference.setUTCHours(12, 0, 0, 0);

  return jobTemplates.map((template, index) => {
    const id = `job-${String(index + 1).padStart(3, "0")}`;
    const postedAt = isoDateFromOffset(stableReference, template.postedOffset);

    return {
      id,
      title: template.title,
      institution: template.institution,
      country: template.country,
      city: template.city,
      research_area: template.research_area,
      language: template.language,
      description: template.description,
      apply_url: `https://example.com/apply/${id}`,
      source_url: `https://example.com/source/${id}`,
      deadline:
        template.deadlineOffset === null
          ? null
          : isoDateFromOffset(stableReference, template.deadlineOffset),
      posted_at: postedAt,
      created_at: isoTimestampFromOffset(stableReference, template.postedOffset),
      employment_type: template.employment_type,
      duration: template.duration,
      tags: [...template.tags],
    };
  });
}
